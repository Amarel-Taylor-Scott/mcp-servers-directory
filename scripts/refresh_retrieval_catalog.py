#!/usr/bin/env python3
"""Rebuild the retrieval snapshot from the pinned upstream revisions.

Run without flags to reproduce the tracked snapshot from GitHub. Use --update to
select the current main commits. For offline use, pass --rag-repo and --ann-repo
pointing to git clones with the pinned objects (local main when using --update).
Use --check to verify the generated bytes without writing. Only data.py is read.
"""
import argparse
import ast
import json
import re
import subprocess
import tempfile
from pathlib import Path
from urllib.request import urlopen

REPOS = {
    "rag": "Amarel-Taylor-Scott/rag-retrievers-rerankers-directory",
    "ann": "Amarel-Taylor-Scott/vector-search-ann-libs-directory",
}
OUTPUT = Path(__file__).resolve().parents[1] / "resources" / "retrieval-catalogs.json"
FIELDS = ("name", "org", "category", "url", "open_source", "license", "note", "tags")


def read_tools(text, source):
    """Read literal Tool(...) rows from TOOLS without executing upstream code."""
    tree = ast.parse(text)
    lists = [node.value for node in tree.body if isinstance(node, ast.AnnAssign)
             and isinstance(node.target, ast.Name) and node.target.id == "TOOLS"]
    if len(lists) != 1 or not isinstance(lists[0], ast.List) or not lists[0].elts:
        raise ValueError(f"{source}: expected one nonempty literal TOOLS list")

    rows = []
    for call in lists[0].elts:
        if not isinstance(call, ast.Call) or not isinstance(call.func, ast.Name) or call.func.id != "Tool":
            raise ValueError(f"{source}: unexpected entry at line {call.lineno}")
        if len(call.args) > len(FIELDS):
            raise ValueError(f"{source}: too many Tool fields at line {call.lineno}")
        values = dict(zip(FIELDS, call.args))
        for keyword in call.keywords:
            if keyword.arg not in FIELDS or keyword.arg in values:
                raise ValueError(f"{source}: unknown or duplicate Tool field at line {call.lineno}")
            values[keyword.arg] = keyword.value
        cat = values.pop("category")
        if not isinstance(cat, ast.Attribute) or not isinstance(cat.value, ast.Name) or cat.value.id != "Category":
            raise ValueError(f"{source}: unsupported category at line {call.lineno}")
        row = {k: ast.literal_eval(v) for k, v in values.items()}
        row["category"] = cat.attr
        row.setdefault("note", "")
        row.setdefault("tags", ())
        if not all(isinstance(row[k], str) and row[k] for k in ("name", "org", "url", "license")):
            raise ValueError(f"{source}: missing Tool metadata at line {call.lineno}")
        if (not isinstance(row["open_source"], bool) or not isinstance(row["note"], str)
                or not isinstance(row["tags"], (list, tuple)) or not all(isinstance(t, str) for t in row["tags"])):
            raise ValueError(f"{source}: unexpected field type at line {call.lineno}")
        slug = re.sub("[^a-z0-9]+", "-", row["name"].lower()).strip("-")
        if not slug or not row["url"].startswith("https://"):
            raise ValueError(f"{source}: invalid name or upstream URL at line {call.lineno}")
        rows.append({"id": f"{source}:{slug}", "source": source, **{k: row[k] for k in FIELDS}})
    return rows


def read_url(url):
    with urlopen(url, timeout=30) as response:
        return response.read()


def git(repo, *args):
    return subprocess.check_output(["git", "-C", str(repo), *args])


def build(sources):
    """Build from source keys mapped to (full commit, UTF-8 source text)."""
    metadata, entries = {}, []
    for source, repository in REPOS.items():
        commit, text = sources[source]
        if not re.fullmatch("[0-9a-f]{40}", commit):
            raise ValueError(f"{source}: expected a full git commit SHA")
        metadata[source] = {"repository": repository, "commit": commit, "path": "data.py",
                            "url": f"https://github.com/{repository}/blob/{commit}/data.py"}
        entries.extend(read_tools(text, source))
    if len({row["id"] for row in entries}) != len(entries):
        raise ValueError("Duplicate stable ID; inspect upstream names before refreshing")
    payload = {"schema_version": 1, "sources": metadata, "entries": sorted(entries, key=lambda r: r["id"])}
    return (json.dumps(payload, ensure_ascii=False, indent=2) + "\n").encode("utf-8")


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--update", action="store_true", help="read upstream main instead of the tracked pins")
    parser.add_argument("--check", action="store_true", help="fail on drift without writing")
    parser.add_argument("--output", type=Path, default=OUTPUT)
    for source in REPOS:
        parser.add_argument(f"--{source}-repo", type=Path, help="read a local git clone instead of GitHub")
    args = parser.parse_args()
    tracked = {} if args.update else json.loads(args.output.read_bytes())["sources"]
    inputs = {}
    for source, repository in REPOS.items():
        local = getattr(args, source + "_repo")
        if args.update:
            commit = (git(local, "rev-parse", "refs/heads/main").decode().strip() if local else
                      json.loads(read_url(f"https://api.github.com/repos/{repository}/commits/main"))["sha"])
        else:
            commit = tracked[source]["commit"]
        if not re.fullmatch("[0-9a-f]{40}", commit):
            parser.error(f"invalid pinned commit for {source}")
        raw = (git(local, "show", f"{commit}:data.py") if local else
               read_url(f"https://raw.githubusercontent.com/{repository}/{commit}/data.py"))
        inputs[source] = commit, raw.decode("utf-8")
    content = build(inputs)
    if args.check:
        if args.output.read_bytes() != content:
            parser.exit(1, "Retrieval snapshot differs from regenerated content\n")
    else:
        args.output.parent.mkdir(parents=True, exist_ok=True)
        with tempfile.NamedTemporaryFile(dir=args.output.parent, delete=False) as tmp:
            tmp.write(content)
        Path(tmp.name).replace(args.output)


if __name__ == "__main__":
    main()
